export const useTranslation = () => {
  const { language } = useSettings();
  
  const t = (key) => {
    const lang = language || 'English';
    if (translations[lang] && translations[lang][key]) {
      return translations[lang][key];
    }
    return key;
  };
  
  return { t };
};
